"""Image layer: generation, rights tagging, manifest, coverage (IR-*)."""

import json
from pathlib import Path

from nandaka.images import (GENERATED_EVIDENCE, ILLUSTRATIVE_EVIDENCE,
                            RIGHTS_CLEARED, RIGHTS_REVIEW, SOURCE_EVIDENCE,
                            ImageLibrary, encode_png, png_bar_chart,
                            structured_image_description, svg_bar_chart,
                            svg_concept_map, svg_flow)


def test_svg_bar_chart_structure_and_labels():
    svg = svg_bar_chart("TPS", {"Constitution": 80.0, "Economy": 55.0})
    assert svg.startswith("<svg") and svg.rstrip().endswith("</svg>")
    assert "Constitution" in svg and "80" in svg
    # IR-03: generated charts state evidence + date
    assert GENERATED_EVIDENCE in svg
    assert "generated by Nandaka" in svg


def test_svg_flow_and_concept_map():
    flow = svg_flow("Process", ["collect", "analyse", "draft"])
    assert "collect" in flow and "Process" in flow
    cmap = svg_concept_map("Map", ["core", "satellite", "edge"],
                           [("core", "satellite"), ("core", "edge")])
    assert cmap.count("<rect") >= 3 and "<line" in cmap


def test_png_encoder_roundtrip_header_and_size():
    png = png_bar_chart("TPS", {"A": 3.0, "B": 5.0}, size=(320, 200))
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    assert b"IHDR" in png and b"IEND" in png
    # IR-07: modest chart stays far below the 200 KB target
    assert len(png) < 200 * 1024
    # raw encoder sanity: 2x2 RGBA
    row = bytes([255, 0, 0, 255] * 2)
    small = encode_png(2, 2, [row, row])
    assert small.startswith(b"\x89PNG")


def test_generated_image_defaults(tmp_path):
    lib = ImageLibrary(tmp_path, max_kb=200)
    rec = lib.add_svg("img-1", svg_bar_chart("T", {"x": 1.0}))
    assert rec.evidence == GENERATED_EVIDENCE
    assert rec.rights == RIGHTS_CLEARED          # original work, cleared
    assert rec.generated_on                       # IR-03 generation date
    assert rec.caption_en and rec.caption_te      # IR-05 bilingual captions
    assert rec.alt_en and rec.alt_te
    assert "not a photograph" in rec.caption_en.lower()


def test_source_derived_unknown_licence_blocked(tmp_path):
    """IR-04: unclear licence -> REVIEW REQUIRED, excluded from export."""
    src = tmp_path / "scan.png"
    from nandaka.images import encode_png
    row = bytes([0, 0, 0, 255] * 4)
    src.write_bytes(encode_png(4, 4, [row] * 4))
    lib = ImageLibrary(tmp_path, max_kb=200)
    rec = lib.adopt_file("img-s1", src, origin=str(src), licence="",
                         caption_en="from doc", caption_te="పత్రం నుండి")
    assert rec.evidence == SOURCE_EVIDENCE
    assert rec.rights == RIGHTS_REVIEW
    assert rec in lib.blocked_images() and rec not in lib.rights_cleared_images()


def test_source_derived_with_licence_cleared(tmp_path):
    src = tmp_path / "pd.png"
    from nandaka.images import encode_png
    row = bytes([9, 9, 9, 255] * 4)
    src.write_bytes(encode_png(4, 4, [row] * 4))
    lib = ImageLibrary(tmp_path)
    rec = lib.adopt_file("img-s2", src, origin="gov portal",
                         licence="Public Domain (Government of India)",
                         attribution="NCERT")
    assert rec.rights == RIGHTS_CLEARED
    assert rec.attribution == "NCERT"
    assert rec in lib.rights_cleared_images()


def test_oversize_note(tmp_path):
    lib = ImageLibrary(tmp_path, max_kb=1)
    big = bytes(2048)
    rec = lib.add_png("img-big", b"\x89PNG\r\n\x1a\n" + big)
    assert any("exceeds target" in c for c in rec.caveats)   # IR-07 reporting


def test_manifest_files_and_fields(tmp_path):
    lib = ImageLibrary(tmp_path)
    lib.add_svg("img-1", svg_bar_chart("T", {"a": 1.0}))
    lib.add_svg("img-2", svg_flow("F", ["s1"]))
    out = tmp_path / "batch"
    out.mkdir()
    paths = lib.write_manifest(out)
    rows = json.loads(Path(paths["json"]).read_text(encoding="utf-8"))
    assert len(rows) == 2
    for key in ("image_id", "origin", "licence", "IMAGE-EVIDENCE",
                "IMAGE-RIGHTS", "caption_en", "caption_te", "alt_en",
                "alt_te", "generated_on"):
        assert key in rows[0], key
    import csv as _csv
    with open(paths["csv"], encoding="utf-8") as fh:
        csv_rows = list(_csv.DictReader(fh))
    assert len(csv_rows) == 2


def test_coverage_reporting_ir17(tmp_path):
    lib = ImageLibrary(tmp_path)
    lib.add_svg("i1", svg_bar_chart("T", {"a": 1}))
    cov = lib.coverage(["Polity", "Economy", "Geography"],
                       {"Polity": 1}, mcq_total=10, mcq_with_image=4)
    assert cov["visual_coverage_pct"] == 33.3
    assert cov["mcq_image_pct"] == 40.0


